'use client';

import { lineAnchor, type AiFinding, type AiFindingSeverity } from '@diffcraft/shared';
import { findingLocation, findingTarget, groupBySeverity } from '@/lib/ai-analysis';
import { useAiAnalysis } from './ai-analysis-provider';
import { smallSecondaryButton, textLink } from './styles';

export const SEVERITY_LABELS: Record<AiFindingSeverity, string> = {
  critical: 'Critical',
  high: 'High',
  medium: 'Medium',
  low: 'Low',
  info: 'Info',
};

const SEVERITY_STYLES: Record<AiFindingSeverity, string> = {
  critical: 'border-rose-700 bg-rose-950/60 text-rose-200',
  high: 'border-orange-700 bg-orange-950/60 text-orange-200',
  medium: 'border-amber-700 bg-amber-950/60 text-amber-200',
  low: 'border-sky-800 bg-sky-950/60 text-sky-200',
  info: 'border-slate-700 bg-slate-900 text-slate-300',
};

const badge = 'rounded-full border px-2 py-0.5 text-[11px] font-medium';

export function AiBadge() {
  return (
    <span
      className={`${badge} border-fuchsia-700 bg-fuchsia-950/60 text-fuchsia-200`}
      title="Generated by AI"
    >
      AI
    </span>
  );
}

export function SeverityBadge({ severity }: { severity: AiFindingSeverity }) {
  return (
    <span className={`${badge} ${SEVERITY_STYLES[severity]}`}>{SEVERITY_LABELS[severity]}</span>
  );
}

const pressed =
  'aria-pressed:border-violet-500 aria-pressed:bg-violet-950/60 aria-pressed:text-violet-100';

export function FindingItem({
  finding,
  compact = false,
}: {
  finding: AiFinding;
  compact?: boolean;
}) {
  const ai = useAiAnalysis();
  if (!ai) return null;
  const target = findingTarget(finding);
  const location = findingLocation(finding);
  const href = target
    ? `${ai.filesHref}#${lineAnchor(target.fileId, target.side, target.line)}`
    : null;
  const error = ai.errors.get(finding.id);
  const busy = ai.pending.has(finding.id);
  const { helpful, notHelpful } = finding.feedback;

  return (
    <article
      aria-label={`AI finding: ${finding.title}`}
      className="space-y-2 rounded-lg border border-slate-800 bg-slate-900 p-3 text-sm"
    >
      <header className="flex flex-wrap items-center gap-2">
        {compact && <AiBadge />}
        {compact && <SeverityBadge severity={finding.severity} />}
        <span className={`${badge} border-slate-700 text-slate-300`}>{finding.category}</span>
        <h4 className="min-w-0 flex-1 font-semibold text-slate-100">{finding.title}</h4>
        <span className="text-xs text-slate-500">
          Confidence {Math.round(finding.confidence * 100)}%
        </span>
      </header>
      {!compact && location && (
        <p className="break-all font-mono text-xs">
          {href ? (
            <a href={href} className={textLink}>
              {location}
            </a>
          ) : (
            <span className="text-slate-400">{location}</span>
          )}
        </p>
      )}
      <p className="whitespace-pre-wrap break-words text-slate-300">{finding.explanation}</p>
      {finding.suggestion && (
        <pre className="overflow-x-auto rounded-md border border-slate-800 bg-slate-950 p-2 font-mono text-xs text-slate-200">
          <code>{finding.suggestion}</code>
        </pre>
      )}
      {ai.canAct && (
        <div className="flex flex-wrap items-center gap-2">
          <button
            type="button"
            aria-pressed={finding.myFeedback === true}
            aria-label={`Helpful (${helpful})`}
            onClick={() => void ai.feedback(finding, true)}
            className={`${smallSecondaryButton} ${pressed}`}
          >
            <span aria-hidden="true">👍 {helpful}</span>
          </button>
          <button
            type="button"
            aria-pressed={finding.myFeedback === false}
            aria-label={`Not helpful (${notHelpful})`}
            onClick={() => void ai.feedback(finding, false)}
            className={`${smallSecondaryButton} ${pressed}`}
          >
            <span aria-hidden="true">👎 {notHelpful}</span>
          </button>
          {ai.canStartThread && target && (
            <button
              type="button"
              disabled={busy}
              onClick={() => void ai.startThread(finding)}
              className={smallSecondaryButton}
            >
              {busy ? 'Starting thread…' : 'Start thread'}
            </button>
          )}
          <button
            type="button"
            aria-label={`Dismiss finding: ${finding.title}`}
            disabled={busy}
            onClick={() => void ai.dismiss(finding)}
            className={smallSecondaryButton}
          >
            Dismiss
          </button>
        </div>
      )}
      {error && (
        <p role="alert" className="text-xs text-red-300">
          {error}
        </p>
      )}
    </article>
  );
}

export function FindingList({ findings }: { findings: AiFinding[] }) {
  return (
    <div className="space-y-4">
      {groupBySeverity(findings).map((group) => (
        <section key={group.severity} aria-label={`${SEVERITY_LABELS[group.severity]} findings`}>
          <h3 className="mb-2 flex items-center gap-2 text-xs font-semibold uppercase tracking-wide text-slate-400">
            <SeverityBadge severity={group.severity} />
            <span>{group.findings.length}</span>
          </h3>
          <div className="space-y-2">
            {group.findings.map((finding) => (
              <FindingItem key={finding.id} finding={finding} />
            ))}
          </div>
        </section>
      ))}
    </div>
  );
}
